// ============================================================
//  Example end-to-end workflow
// ============================================================

// RunE2EWorkflow is a self-contained demo that exercises the full system.
func RunE2EWorkflow(c *PolyClient, logger *zap.Logger) error {
	logger.Info("=== Starting E2E Workflow ===")

	// 1. Register
	regResp, err := c.Register("alice", "alice@example.com", "Password123!", "0xALICE")
	if err != nil {
		return fmt.Errorf("register: %w", err)
	}
	logger.Info("registered", zap.String("user_id", regResp.User.ID))
	c.SetToken(regResp.Token)

	// 2. Deposit funds
	depResp, err := c.Deposit(5000, "initial-deposit-001")
	if err != nil {
		return fmt.Errorf("deposit: %w", err)
	}
	logger.Info("deposited", zap.Float64("balance", depResp.Wallet.Balance))

	// 3. List markets
	mkts, err := c.ListMarkets("", 1, 10)
	if err != nil {
		return fmt.Errorf("list markets: %w", err)
	}
	if len(mkts.Markets) == 0 {
		return fmt.Errorf("no markets found")
	}
	firstMarket := mkts.Markets[0]
	logger.Info("found market",
		zap.String("title", firstMarket.Title),
		zap.Float64("yes_prob", firstMarket.YesProbability),
	)

	// 4. Place a BUY YES order
	orderResp, err := c.BuyYes(firstMarket.ID, 100.0, 0.65)
	if err != nil {
		return fmt.Errorf("buy yes: %w", err)
	}
	logger.Info("placed order",
		zap.String("order_id", orderResp.Order.ID),
		zap.String("status", string(orderResp.Order.Status)),
	)

	// 5. Check order book
	book, err := c.GetOrderBook(firstMarket.ID)
	if err != nil {
		return fmt.Errorf("order book: %w", err)
	}
	logger.Info("order book",
		zap.Int("bids", len(book.Bids)),
		zap.Int("asks", len(book.Asks)),
	)

	// 6. Check wallet balance
	walletResp, err := c.GetWallet()
	if err != nil {
		return fmt.Errorf("get wallet: %w", err)
	}
	logger.Info("wallet balance",
		zap.Float64("balance", walletResp.Wallet.Balance),
		zap.Float64("locked", walletResp.Wallet.LockedBalance),
	)

	logger.Info("=== E2E Workflow Complete ===")
	return nil
}
