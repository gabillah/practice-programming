// Package client provides a typed Go client for all Polymarket gRPC services.
// Use this in CLI tools, integration tests, or other microservices.
package client

import (
	"context"
	"fmt"
	"time"

	"go.uber.org/zap"
	"google.golang.org/grpc"
	"google.golang.org/grpc/credentials/insecure"
	"google.golang.org/grpc/metadata"

	"github.com/polymarket-grpc/models"
	mktSvc "github.com/polymarket-grpc/services/market"
	ordSvc "github.com/polymarket-grpc/services/order"
	usrSvc "github.com/polymarket-grpc/services/user"
	walSvc "github.com/polymarket-grpc/services/wallet"
)

// PolyClient is a single client that connects to all Polymarket services.
// When connecting to a real gRPC server you would swap the in-process
// calls for real gRPC stub calls generated by protoc.
type PolyClient struct {
	userSvc   *usrSvc.Server
	marketSvc *mktSvc.Server
	orderSvc  *ordSvc.Server
	walletSvc *walSvc.Server
	token     string
	logger    *zap.Logger
}

// NewPolyClient creates a client pointing at the given gRPC address.
// In this project we accept the concrete service servers directly so that
// the code can be demonstrated without a running network server.
func NewPolyClient(
	userSvr *usrSvc.Server,
	marketSvr *mktSvc.Server,
	orderSvr *ordSvc.Server,
	walletSvr *walSvc.Server,
	logger *zap.Logger,
) *PolyClient {
	return &PolyClient{
		userSvc:   userSvr,
		marketSvc: marketSvr,
		orderSvc:  orderSvr,
		walletSvc: walletSvr,
		logger:    logger,
	}
}

// NewGRPCConn is a helper that establishes a plain-text gRPC connection.
// Use this when talking to a real remote gRPC server.
func NewGRPCConn(addr string) (*grpc.ClientConn, error) {
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	conn, err := grpc.DialContext(
		ctx,
		addr,
		grpc.WithTransportCredentials(insecure.NewCredentials()),
		grpc.WithBlock(),
	)
	if err != nil {
		return nil, fmt.Errorf("dial %s: %w", addr, err)
	}
	return conn, nil
}

// SetToken stores a bearer token that will be attached to every request.
func (c *PolyClient) SetToken(token string) {
	c.token = token
}

// ctx returns a context enriched with the stored bearer token as
// gRPC metadata, so that the server-side auth interceptors pass.
func (c *PolyClient) ctx() context.Context {
	if c.token == "" {
		return context.Background()
	}
	md := metadata.New(map[string]string{
		"authorization": "Bearer " + c.token,
	})
	return metadata.NewIncomingContext(context.Background(), md)
}

// ============================================================
//  User Operations
// ============================================================

func (c *PolyClient) Register(username, email, password, wallet string) (*usrSvc.CreateUserResponse, error) {
	return c.userSvc.CreateUser(context.Background(), &usrSvc.CreateUserRequest{
		Username:      username,
		Email:         email,
		Password:      password,
		WalletAddress: wallet,
	})
}

func (c *PolyClient) Login(email, password string) (*usrSvc.AuthenticateResponse, error) {
	resp, err := c.userSvc.Authenticate(context.Background(), &usrSvc.AuthenticateRequest{
		Email:    email,
		Password: password,
	})
	if err != nil {
		return nil, err
	}
	c.SetToken(resp.Token)
	return resp, nil
}

func (c *PolyClient) GetUser(id string) (*usrSvc.GetUserResponse, error) {
	return c.userSvc.GetUser(c.ctx(), &usrSvc.GetUserRequest{ID: id})
}

